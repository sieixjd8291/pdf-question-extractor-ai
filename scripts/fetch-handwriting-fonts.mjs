// Downloads the handwriting font catalog used by Assignment Maker into
// public/fonts/handwriting and writes a self-hosted fonts.css. Run once with
// `node scripts/fetch-handwriting-fonts.mjs`; the output is committed so the
// app never requests fonts from a third-party origin at runtime.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const FAMILIES = [
  'Homemade Apple', 'Cedarville Cursive', 'La Belle Aurore', 'Dancing Script', 'Sacramento',
  'Satisfy', 'Mrs Saint Delafield', 'Zeyada', 'Dawning of a New Day', 'Nothing You Could Do',
  'Waiting for the Sunrise', 'Marck Script', 'Kristi', 'Caveat', 'Kalam', 'Indie Flower',
  'Shadows Into Light', 'Patrick Hand', 'Gochi Hand', 'Reenie Beanie', 'Architects Daughter',
  'Gloria Hallelujah', 'Just Another Hand', 'Covered By Your Grace', 'Over the Rainbow',
  'Nanum Pen Script', 'Neucha', 'Schoolbell', 'Coming Soon', 'Annie Use Your Telescope',
  'Handlee', 'Sue Ellen Francisco', 'Loved by the King', 'Rock Salt', 'Amita', 'Delius',
];
const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'devanagari', 'greek']);
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

const outDir = path.resolve('public/fonts/handwriting');
await mkdir(outDir, { recursive: true });
let css = '/* Generated by scripts/fetch-handwriting-fonts.mjs */\n';

for (const family of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) { console.warn('skip', family, res.status); continue; }
  const text = await res.text();
  const blocks = [...text.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g)];
  let index = 0;
  for (const [, subset, body] of blocks) {
    if (!KEEP_SUBSETS.has(subset)) continue;
    const src = body.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    if (!src) continue;
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1] ?? '';
    const file = `${family.toLowerCase().replace(/\s+/g, '-')}-${subset}-${index++}.woff2`;
    const bin = Buffer.from(await (await fetch(src)).arrayBuffer());
    await writeFile(path.join(outDir, file), bin);
    css += `@font-face{font-family:'${family}';font-style:normal;font-weight:400;font-display:swap;src:url('/fonts/handwriting/${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}\n`;
  }
  console.log('ok', family);
}

await writeFile(path.join(outDir, 'fonts.css'), css);
console.log('done');
