// Downloads Google Fonts (OFL) as self-hosted woff2 files and appends their
// @font-face rules to public/fonts/handwriting/fonts.css.
// Usage: node scripts/fetch-handwriting-fonts.mjs "Font One" "Font Two" ...
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const OUT_DIR = path.resolve('public/fonts/handwriting');
const CSS_FILE = path.join(OUT_DIR, 'fonts.css');
const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext', 'devanagari', 'vietnamese']);
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

async function fetchFamily(family) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family).replace(/%20/g, '+')}&display=swap`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${family}: HTTP ${res.status}`);
  const css = await res.text();
  const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g)];
  const kept = blocks.filter(([, subset]) => KEEP_SUBSETS.has(subset));
  if (!kept.length) throw new Error(`${family}: no usable subsets`);

  const slug = slugify(family);
  const rules = [];
  for (let i = 0; i < kept.length; i++) {
    const [, subset, body] = kept[i];
    const src = body.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    const range = body.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!src) continue;
    const file = `${slug}-${subset}-${i}.woff2`;
    const bin = Buffer.from(await (await fetch(src)).arrayBuffer());
    await writeFile(path.join(OUT_DIR, file), bin);
    rules.push(
      `@font-face{font-family:'${family}';font-style:normal;font-weight:400;font-display:swap;src:url('/fonts/handwriting/${file}') format('woff2');${range ? `unicode-range:${range};` : ''}}`,
    );
  }
  return rules;
}

const families = process.argv.slice(2);
if (!families.length) {
  console.error('Pass one or more Google Font family names.');
  process.exit(1);
}

await mkdir(OUT_DIR, { recursive: true });
let css = await readFile(CSS_FILE, 'utf8').catch(() => '/* Generated by scripts/fetch-handwriting-fonts.mjs */\n');
const failed = [];
for (const family of families) {
  if (css.includes(`font-family:'${family}'`)) {
    console.log(`skip  ${family} (already present)`);
    continue;
  }
  try {
    const rules = await fetchFamily(family);
    css = css.trimEnd() + '\n' + rules.join('\n') + '\n';
    console.log(`added ${family} (${rules.length} files)`);
  } catch (err) {
    failed.push(family);
    console.error(`fail  ${err.message}`);
  }
}
await writeFile(CSS_FILE, css);
if (failed.length) process.exitCode = 1;
